function LenderShareCard({ r, company }: { r: SettlementResult; company: string }) {
  const [copied, setCopied] = useState<"yes" | "no" | null>(null);
  const [origin, setOrigin] = useState("");
  useEffect(() => { setOrigin(window.location.origin); }, []);
  const url = `${origin}${shareFragment(r.lenderShare)}`;
  const copy = async () => {
    try { await navigator.clipboard.writeText(url); setCopied("yes"); } catch { setCopied("no"); }
    setTimeout(() => setCopied(null), 2500);
  };
  return (
    <Card>
      <div className="flex flex-wrap items-start justify-between gap-4">
        <div className="max-w-2xl">
          <Eyebrow>Share with your lender</Eyebrow>
          <h2 className="mt-2 font-display text-[26px] leading-tight tracking-tight">Prove the cover to your lender, not to the world</h2>
          <p className="mt-2 text-[13px] leading-relaxed text-muted">Your lender or factoring company can read this policy&apos;s coverage and payouts with this link but cannot spend: it carries read-only viewing keys for the {r.lenderShare.steps.length} step vaults, and the keys travel in the part of the URL after #, which browsers do not send when loading a page.</p>
        </div>
        <a href={shareFragment(r.lenderShare)} target="_blank" rel="noreferrer" className="inline-flex items-center justify-center gap-2 rounded-full border border-line bg-surface px-5 py-2.5 text-sm font-medium text-ink transition-colors hover:border-ink/40">Open the lender view ↗</a>
      </div>
      <div className="mt-4 flex flex-col gap-2 sm:flex-row lg:flex-col xl:flex-row">
        <input readOnly value={url} onFocus={(e) => e.currentTarget.select()} aria-label={`Lender link for ${company}`} className="min-w-0 flex-1 rounded-full border border-line bg-paper px-4 py-2.5 font-mono text-[12px] text-muted" />
        <Button onClick={copy} className="shrink-0">{copied === "yes" ? "Copied" : copied === "no" ? "Copy failed: select and copy" : "Copy link"}</Button>
      </div>
      <p className="mt-2 text-xs text-faint">Anyone holding the link can read these amounts, so send it only to your lender. In this demo the lender page asks the CostShield server to decrypt with the keys in the link.</p>
    </Card>
  );
}
