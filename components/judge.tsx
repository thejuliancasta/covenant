                <p className="mt-2 text-xs text-faint">Venue fees and collateral are not included: they were not verified. One fleet nearly fits; a pool of {a.pool?.sizing.fleetsPerContractMonth ?? "many"} does not, and the contracts expire in {m.crude.implied.days.toFixed(0)} days.</p>
